#ifndef LLVM_LIB_TARGET_CGP1_CGP1SUBTARGET_H
#define LLVM_LIB_TARGET_CGP1_CGP1SUBTARGET_H

#include "CGP1FrameLowering.h"
#include "CGP1ISelLowering.h"
#include "CGP1InstrInfo.h"
#include "CGP1SelectionDAGInfo.h"
#include "llvm/CodeGen/TargetSubtargetInfo.h"
#include "llvm/IR/DataLayout.h"
#include "llvm/Target/TargetMachine.h"

#define GET_SUBTARGETINFO_HEADER
#include "CGP1GenSubtargetInfo.inc"

namespace llvm {

class CGP1Subtarget : public CGP1GenSubtargetInfo {
public:
  // This constructor initializes the data members to match that
  // of the specified triple.
  CGP1Subtarget(const Triple &TargetTriple, StringRef Cpu,
                 StringRef FeatureString, const TargetMachine &TM,
                 const TargetOptions &Options, CodeModel::Model CodeModel,
                 CodeGenOptLevel OptLevel);

  // ParseSubtargetFeatures - Parses features string setting specified
  // subtarget options.  Definition of function is auto generated by tblgen.
  void ParseSubtargetFeatures(StringRef CPU, StringRef TuneCPU, StringRef FS);

  CGP1Subtarget &initializeSubtargetDependencies(StringRef CPU, StringRef FS);

  void initSubtargetFeatures(StringRef CPU, StringRef FS);

  bool enableMachineScheduler() const override { return true; }

  const CGP1InstrInfo *getInstrInfo() const override { return &InstrInfo; }

  const TargetFrameLowering *getFrameLowering() const override {
    return &FrameLowering;
  }

  const CGP1RegisterInfo *getRegisterInfo() const override {
    return &InstrInfo.getRegisterInfo();
  }

  const CGP1TargetLowering *getTargetLowering() const override {
    return &TLInfo;
  }

  const CGP1SelectionDAGInfo *getSelectionDAGInfo() const override {
    return &TSInfo;
  }

private:
  CGP1FrameLowering FrameLowering;
  CGP1InstrInfo InstrInfo;
  CGP1TargetLowering TLInfo;
  CGP1SelectionDAGInfo TSInfo;
};
} // namespace llvm

#endif // LLVM_LIB_TARGET_CGP1_CGP1SUBTARGET_H

#ifndef LLVM_LIB_TARGET_CGP1_CGP1SUBTARGET_H
#define LLVM_LIB_TARGET_CGP1_CGP1SUBTARGET_H

#include "CGP1FrameLowering.h"
#include "CGP1ISelLowering.h"
#include "CGP1InstrInfo.h"
#include "CGP1RegisterInfo.h"
#include "llvm/CodeGen/SelectionDAGTargetInfo.h"
#include "llvm/CodeGen/TargetSubtargetInfo.h"
#include "llvm/IR/DataLayout.h"

#define GET_SUBTARGETINFO_HEADER
#include "CGP1GenSubtargetInfo.inc"
//- cgp1-subtarget-1

//@s cgp1-subtarget-2 end
namespace llvm {
class CGP1Subtarget : public CGP1GenSubtargetInfo {
protected:
  SelectionDAGTargetInfo TSInfo;
  CGP1InstrInfo InstrInfo;
  CGP1FrameLowering FrameLowering;
  CGP1TargetLowering TLInfo;
  CGP1RegisterInfo RegInfo;
  //- cgp1-subtarget-2
  //@s cgp1-subtarget-3
public:
  CGP1Subtarget(const Triple &TT, StringRef CPU, StringRef FS,
                const TargetMachine &TM)
      : CGP1GenSubtargetInfo(TT, CPU, CPU, FS), InstrInfo(*this),
        FrameLowering(*this, Align(8)), TLInfo(TM, *this) {}

  const CGP1RegisterInfo *getRegisterInfo() const override { return &RegInfo; }

  const CGP1InstrInfo *getInstrInfo() const override { return &InstrInfo; }

  const CGP1FrameLowering *getFrameLowering() const override {
    return &FrameLowering;
  }

  const CGP1TargetLowering *getTargetLowering() const override {
    return &TLInfo;
  }

  const SelectionDAGTargetInfo *getSelectionDAGInfo() const override {
    return &TSInfo;
  }
  /// ParseSubtargetFeatures - Parses features string setting specified
  /// subtarget options.  Definition of function is auto generated by tblgen.
  void ParseSubtargetFeatures(StringRef CPU, StringRef TuneCPU, StringRef FS);
};

} // end namespace llvm
#endif

